import java.io.File
import java.security.MessageDigest

/**
 * The Strata glyph bundle (ARCHITECTURE §9.1, FR-THEME-35, T-THEME-55), checked and versioned at build time.
 * The index is `res/raw/glyph_index.txt` (`<package> <glyph id>` per line, `#` comments); each id has a
 * `res/drawable-nodpi/glyph_<id>.xml` single-colour vector. The version is a hash over the index bytes and the bytes
 * of every referenced drawable, so a changed index or glyph artwork changes the icon cache key with no manual step.
 */
object GlyphBundleLogic {
    private val PACKAGE = Regex("^[A-Za-z][A-Za-z0-9_]*(\\.[A-Za-z][A-Za-z0-9_]*)+$")
    private val GLYPH_ID = Regex("^[a-z0-9_]{1,64}$")

    data class Entry(val packageName: String, val glyphId: String)

    /** Strict parse of the production index: every problem is reported (the build fails on any). */
    fun parse(text: String): Pair<List<Entry>, List<String>> {
        val entries = mutableListOf<Entry>()
        val problems = mutableListOf<String>()
        val seen = hashSetOf<String>()
        text.lines().forEachIndexed { i, raw ->
            val line = raw.substringBefore('#').trim()
            if (line.isEmpty()) return@forEachIndexed
            val parts = line.split(Regex("\\s+"))
            when {
                parts.size != 2 -> problems += "line ${i + 1}: expected '<package> <glyph id>'"
                !PACKAGE.matches(parts[0]) -> problems += "line ${i + 1}: invalid package name '${parts[0]}'"
                !GLYPH_ID.matches(parts[1]) -> problems += "line ${i + 1}: invalid glyph id '${parts[1]}'"
                !seen.add(parts[0]) -> problems += "line ${i + 1}: duplicate package '${parts[0]}'"
                else -> entries += Entry(parts[0], parts[1])
            }
        }
        return entries to problems
    }

    /**
     * Problems of one glyph drawable: a `<vector>` root, at least one path, a single fill colour, no strokes,
     * gradients or bitmaps (THEME_SYSTEM §4.6: one consistent single-colour style; the fill is replaced by the tint).
     */
    fun drawableProblems(
        name: String,
        xml: String,
    ): List<String> {
        val problems = mutableListOf<String>()
        val body = xml.replace(Regex("<!--.*?-->", RegexOption.DOT_MATCHES_ALL), "")
        val root = Regex("<([A-Za-z][\\w.-]*)").find(body.replace(Regex("<\\?.*?\\?>"), ""))?.groupValues?.get(1)
        if (root != "vector") problems += "$name: root element must be <vector>"
        if (!body.contains("<path")) problems += "$name: no <path>"
        val fills = Regex("android:fillColor\\s*=\\s*\"([^\"]*)\"").findAll(body).map { it.groupValues[1] }.toSet()
        if (fills.size != 1) problems += "$name: expected exactly one fill colour, found ${fills.size}"
        for (forbidden in listOf("android:strokeColor", "<gradient", "<bitmap", "<aapt:attr", "<clip-path")) {
            if (body.contains(forbidden)) problems += "$name: '$forbidden' is not allowed in a glyph"
        }
        return problems
    }

    /** Hash over the index and every referenced glyph (sorted by id); 16 hex chars. */
    fun version(
        index: ByteArray,
        glyphs: Map<String, ByteArray>,
    ): String {
        val md = MessageDigest.getInstance("SHA-256")
        md.update("strata-glyphs-v1\n".toByteArray())
        md.update(index.size.toString().toByteArray())
        md.update(0)
        md.update(index)
        for ((id, bytes) in glyphs.toSortedMap()) {
            md.update(id.toByteArray())
            md.update(0)
            md.update(bytes.size.toString().toByteArray())
            md.update(0)
            md.update(bytes)
        }
        return md.digest().take(8).joinToString("") { "%02x".format(it) }
    }

    /** Kotlin source of `GlyphBundle` in [packageName]: the version and the glyph id → drawable map. */
    fun source(
        packageName: String,
        version: String,
        ids: Collection<String>,
    ): String =
        buildString {
            appendLine("// Generated by build-logic GlyphBundleLogic. Do not edit.")
            appendLine("package $packageName")
            appendLine()
            appendLine("/** The bundled glyphs (ARCHITECTURE 9.1): build-time version and glyph id to drawable. */")
            appendLine("internal object GlyphBundle {")
            appendLine("    const val VERSION: String = \"$version\"")
            appendLine()
            appendLine("    val DRAWABLES: Map<String, Int> =")
            appendLine("        mapOf(")
            for (id in ids.toSortedSet()) appendLine("            \"$id\" to R.drawable.glyph_$id,")
            appendLine("        )")
            appendLine("}")
        }

    /** One glyph set: an index file and the directory of its `glyph_<id>.xml` drawables. */
    data class GlyphSet(
        val name: String,
        val index: File,
        val drawables: File,
    )

    /** Result of [check]: the bundle version, the referenced ids, and the merged index that is packaged. */
    data class Checked(
        val version: String,
        val ids: List<String>,
        val mergedIndex: ByteArray,
    )

    /**
     * The packaged index: the public index bytes unchanged, followed by the private overlay's when there is one.
     * Without an overlay the result is byte-identical to the public index, so the bundle version is unchanged.
     */
    fun mergeIndex(
        public: ByteArray,
        overlay: ByteArray?,
    ): ByteArray {
        if (overlay == null) return public
        val sep = if (public.isEmpty() || public.last() == '\n'.code.toByte()) "" else "\n"
        return public + "$sep# --- private overlay ---\n".toByteArray() + overlay
    }

    /** Every check of the bundle; returns the version and the referenced ids, or throws with all problems. */
    fun check(
        indexFile: File,
        drawableDir: File,
    ): Pair<String, List<String>> = check(GlyphSet("public", indexFile, drawableDir), null).let { it.version to it.ids }

    /**
     * Every check of the public set plus an optional private overlay (CONTRIBUTING "Public mirror and CI"): each
     * index parses strictly, no package appears in both, every id has a single-colour vector in either set, and no
     * overlay drawable redefines a public glyph id. Throws with all problems.
     */
    fun check(
        public: GlyphSet,
        overlay: GlyphSet?,
    ): Checked {
        val sets = listOfNotNull(public, overlay)
        val all = mutableListOf<String>()
        val bytes = sets.associateWith { it.index.readBytes() }
        val owner = hashMapOf<String, String>()
        val ids = mutableListOf<String>()
        for (set in sets) {
            val (entries, problems) = parse(String(bytes.getValue(set), Charsets.UTF_8))
            all += problems.map { if (overlay == null) it else "${set.name} index: $it" }
            for (e in entries) {
                val first = owner.putIfAbsent(e.packageName, set.name)
                if (first != null) all += "duplicate package '${e.packageName}' in the $first and ${set.name} indexes"
                if (e.glyphId !in ids) ids += e.glyphId
            }
        }
        val glyphFiles = sets.map { set -> set.drawables.listFiles { f -> f.isFile && f.name.startsWith("glyph_") } }
        if (overlay != null) {
            val publicNames = glyphFiles[0].orEmpty().map { it.name }.toSet()
            for (f in glyphFiles[1].orEmpty().filter { it.name in publicNames }.sortedBy { it.name }) {
                all += "${f.name}: the ${overlay.name} set must not redefine a ${public.name} glyph"
            }
        }
        val glyphs = linkedMapOf<String, ByteArray>()
        for (id in ids) {
            val file = sets.map { File(it.drawables, "glyph_$id.xml") }.firstOrNull { it.isFile }
            if (file == null) {
                all +=
                    "glyph '$id': missing glyph_$id.xml in " +
                    sets.joinToString(" or ") { "${it.name} ${it.drawables.name}/" }
                continue
            }
            val b = file.readBytes()
            all += drawableProblems(file.name, String(b, Charsets.UTF_8))
            glyphs[id] = b
        }
        if (all.isNotEmpty()) throw GradleException("Glyph bundle (T-THEME-55):\n" + all.joinToString("\n"))
        val merged = mergeIndex(bytes.getValue(public), overlay?.let { bytes.getValue(it) })
        return Checked(version(merged, glyphs), ids, merged)
    }
}

/**
 * Generates `GlyphBundle.kt` for `:platform:icons` after [GlyphBundleLogic.check], and the packaged
 * `res/raw/glyph_index.txt` (the public index merged with the optional private overlay) in [resOutput].
 */
@CacheableTask
abstract class GenerateGlyphBundle : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val index: RegularFileProperty

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val drawables: DirectoryProperty

    /** Private overlay index (absent on the public mirror). */
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val overlayIndex: RegularFileProperty

    /** Private overlay drawables (absent on the public mirror). */
    @get:InputDirectory
    @get:Optional
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val overlayDrawables: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @get:OutputDirectory
    abstract val resOutput: DirectoryProperty

    @TaskAction
    fun generate() {
        val public = GlyphBundleLogic.GlyphSet("public", index.get().asFile, drawables.get().asFile)
        val overlay =
            if (overlayIndex.isPresent) {
                GlyphBundleLogic.GlyphSet(
                    "private",
                    overlayIndex.get().asFile,
                    overlayDrawables.orNull?.asFile ?: File(overlayIndex.get().asFile.parentFile, "missing"),
                )
            } else {
                null
            }
        val checked = GlyphBundleLogic.check(public, overlay)
        val root = output.get().asFile
        root.deleteRecursively()
        val dir = File(root, packageName.get().replace('.', '/')).apply { mkdirs() }
        File(dir, "GlyphBundle.kt").writeText(GlyphBundleLogic.source(packageName.get(), checked.version, checked.ids))
        val res = resOutput.get().asFile
        res.deleteRecursively()
        File(res, "raw").apply { mkdirs() }.resolve("glyph_index.txt").writeBytes(checked.mergedIndex)
    }
}
