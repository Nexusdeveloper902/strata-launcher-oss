import java.security.MessageDigest

/**
 * The Strata glyph bundle (ARCHITECTURE §9.1, FR-THEME-35, T-THEME-55), checked and versioned at build time.
 * The index is `res/raw/glyph_index.txt` (`<package> <glyph id>` per line, `#` comments); each id has a
 * `res/drawable-nodpi/glyph_<id>.xml` single-colour vector. The version is a hash over the index bytes and the bytes
 * of every referenced drawable, so a changed index or glyph artwork changes the icon cache key with no manual step.
 */
object GlyphBundleLogic {
    private val PACKAGE = Regex("^[A-Za-z][A-Za-z0-9_]*(\\.[A-Za-z][A-Za-z0-9_]*)+$")
    private val GLYPH_ID = Regex("^[a-z0-9_]{1,64}$")

    data class Entry(val packageName: String, val glyphId: String)

    /** Strict parse of the production index: every problem is reported (the build fails on any). */
    fun parse(text: String): Pair<List<Entry>, List<String>> {
        val entries = mutableListOf<Entry>()
        val problems = mutableListOf<String>()
        val seen = hashSetOf<String>()
        text.lines().forEachIndexed { i, raw ->
            val line = raw.substringBefore('#').trim()
            if (line.isEmpty()) return@forEachIndexed
            val parts = line.split(Regex("\\s+"))
            when {
                parts.size != 2 -> problems += "line ${i + 1}: expected '<package> <glyph id>'"
                !PACKAGE.matches(parts[0]) -> problems += "line ${i + 1}: invalid package name '${parts[0]}'"
                !GLYPH_ID.matches(parts[1]) -> problems += "line ${i + 1}: invalid glyph id '${parts[1]}'"
                !seen.add(parts[0]) -> problems += "line ${i + 1}: duplicate package '${parts[0]}'"
                else -> entries += Entry(parts[0], parts[1])
            }
        }
        return entries to problems
    }

    /**
     * Problems of one glyph drawable: a `<vector>` root, at least one path, a single fill colour, no strokes,
     * gradients or bitmaps (THEME_SYSTEM §4.6: one consistent single-colour style; the fill is replaced by the tint).
     */
    fun drawableProblems(
        name: String,
        xml: String,
    ): List<String> {
        val problems = mutableListOf<String>()
        val body = xml.replace(Regex("<!--.*?-->", RegexOption.DOT_MATCHES_ALL), "")
        val root = Regex("<([A-Za-z][\\w.-]*)").find(body.replace(Regex("<\\?.*?\\?>"), ""))?.groupValues?.get(1)
        if (root != "vector") problems += "$name: root element must be <vector>"
        if (!body.contains("<path")) problems += "$name: no <path>"
        val fills = Regex("android:fillColor\\s*=\\s*\"([^\"]*)\"").findAll(body).map { it.groupValues[1] }.toSet()
        if (fills.size != 1) problems += "$name: expected exactly one fill colour, found ${fills.size}"
        for (forbidden in listOf("android:strokeColor", "<gradient", "<bitmap", "<aapt:attr", "<clip-path")) {
            if (body.contains(forbidden)) problems += "$name: '$forbidden' is not allowed in a glyph"
        }
        return problems
    }

    /** Hash over the index and every referenced glyph (sorted by id); 16 hex chars. */
    fun version(
        index: ByteArray,
        glyphs: Map<String, ByteArray>,
    ): String {
        val md = MessageDigest.getInstance("SHA-256")
        md.update("strata-glyphs-v1\n".toByteArray())
        md.update(index.size.toString().toByteArray())
        md.update(0)
        md.update(index)
        for ((id, bytes) in glyphs.toSortedMap()) {
            md.update(id.toByteArray())
            md.update(0)
            md.update(bytes.size.toString().toByteArray())
            md.update(0)
            md.update(bytes)
        }
        return md.digest().take(8).joinToString("") { "%02x".format(it) }
    }

    /** Kotlin source of `GlyphBundle` in [packageName]: the version and the glyph id → drawable map. */
    fun source(
        packageName: String,
        version: String,
        ids: Collection<String>,
    ): String =
        buildString {
            appendLine("// Generated by build-logic GlyphBundleLogic. Do not edit.")
            appendLine("package $packageName")
            appendLine()
            appendLine("/** The bundled glyphs (ARCHITECTURE 9.1): build-time version and glyph id to drawable. */")
            appendLine("internal object GlyphBundle {")
            appendLine("    const val VERSION: String = \"$version\"")
            appendLine()
            appendLine("    val DRAWABLES: Map<String, Int> =")
            appendLine("        mapOf(")
            for (id in ids.toSortedSet()) appendLine("            \"$id\" to R.drawable.glyph_$id,")
            appendLine("        )")
            appendLine("}")
        }

    /** Every check of the bundle; returns the version and the referenced ids, or throws with all problems. */
    fun check(
        indexFile: File,
        drawableDir: File,
    ): Pair<String, List<String>> {
        val indexBytes = indexFile.readBytes()
        val (entries, problems) = parse(String(indexBytes, Charsets.UTF_8))
        val all = problems.toMutableList()
        val ids = entries.map { it.glyphId }.distinct()
        val glyphs = linkedMapOf<String, ByteArray>()
        for (id in ids) {
            val file = File(drawableDir, "glyph_$id.xml")
            if (!file.isFile) {
                all += "glyph '$id': missing ${file.name} in ${drawableDir.name}/"
                continue
            }
            val bytes = file.readBytes()
            all += drawableProblems(file.name, String(bytes, Charsets.UTF_8))
            glyphs[id] = bytes
        }
        if (all.isNotEmpty()) throw GradleException("Glyph bundle (T-THEME-55):\n" + all.joinToString("\n"))
        return version(indexBytes, glyphs) to ids
    }
}

/** Generates `GlyphBundle.kt` for `:platform:icons` after [GlyphBundleLogic.check]. */
@CacheableTask
abstract class GenerateGlyphBundle : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val index: RegularFileProperty

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val drawables: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val (version, ids) = GlyphBundleLogic.check(index.get().asFile, drawables.get().asFile)
        val root = output.get().asFile
        root.deleteRecursively()
        val dir = File(root, packageName.get().replace('.', '/')).apply { mkdirs() }
        File(dir, "GlyphBundle.kt").writeText(GlyphBundleLogic.source(packageName.get(), version, ids))
    }
}
